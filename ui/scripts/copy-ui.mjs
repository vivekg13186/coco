// Copies the generated site into the engine package, so the built UI can live in git
// and `coco-server` serves it without anyone running npm. Run via `npm run build`.
import { cpSync, existsSync, rmSync, writeFileSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'

const ui = join(dirname(fileURLToPath(import.meta.url)), '..')
const from = join(ui, '.output', 'public')
const to = join(ui, '..', 'server', 'coco_server', 'ui')

if (!existsSync(join(from, 'index.html'))) {
  console.error(`no build found at ${from}; run "nuxt generate" first`)
  process.exit(1)
}
rmSync(to, { recursive: true, force: true })
cpSync(from, to, { recursive: true })
writeFileSync(join(to, 'BUILT_FROM_UI.txt'),
  'Generated by `npm run build` in ui/. Do not edit: change ui/ and build again.\n')
console.log(`copied the built UI to ${to}`)
